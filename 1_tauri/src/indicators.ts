/**
 * Indicator implementations in TS.
 *
 * Two paths, for comparison:
 *  - `computeAllTalib` uses the TA-Lib C library compiled to WASM (`talib-wasm`
 *    npm package, emscripten build of the official ta-lib.org source — the
 *    official TA-Lib org TypeScript port is not yet published on npm).
 *    Used for EMA/SMA; VWAP and the volume profile have no TA-Lib equivalent
 *    and use the pure-JS reference below.
 *  - `computeAllJs` is a pure-JS port of `shared/indicators` (the Rust
 *    reference implementations), kept as fallback + test oracle.
 *
 * Parity is unit-tested against golden files generated by
 * `src-tauri/src/bin/gen_golden.rs` (see `src/indicators.test.ts`).
 */

import type { Bar, Indicators, ProfileBin } from './types';

// ---------------------------------------------------------------------------
// TA-Lib WASM plumbing
//
// `talib-wasm`'s JS wrapper (wrap-talib-function.js) has a heap-corrupting bug:
// it calls `Module._free(offset / 8)` on byte pointers returned by `_malloc`,
// which OOMs on 23k-bar inputs. We therefore load the raw emscripten module
// factory (`talib-wasm/build/talib.wrapped.min.js`) and call the C functions
// TA_EMA/TA_SMA directly via cwrap with correct pointer handling.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type TalibModule = any;

// The emscripten bundle is compiled CJS and relies on sloppy-mode `this`
// (its ready-promise executor reads `this.abort`). Bundled as ESM it becomes
// strict and throws. We therefore load it as raw text and evaluate it inside
// `new Function` — a sloppy context with a fake `module.exports` — which
// preserves its expected runtime semantics.
import talibSrc from 'talib-wasm/build/talib.wrapped.min.js?raw';

let talibModulePromise: Promise<TalibModule> | null = null;
const cwrapped: Record<string, (...args: number[]) => number> = {};

export function initTalib(): Promise<TalibModule> {
  if (!talibModulePromise) {
    talibModulePromise = (async () => {
      const fakeModule: { exports: unknown } = { exports: {} };
      // eslint-disable-next-line @typescript-eslint/no-implied-eval
      const makeModule = new Function('module', 'exports', 'require', `${talibSrc}\n;return module.exports;`)(
        fakeModule,
        fakeModule.exports,
        () => ({}),
      ) as () => Promise<TalibModule>;
      return await makeModule();
    })();
  }
  return talibModulePromise;
}

/**
 * Call a TA-Lib function with signature
 *   (startIdx, endIdx, inReal[], optInTimePeriod, outBegIdx*, outNBElement*, outReal[])
 * Returns a (number|null)[] aligned to the input (null during lookback warmup).
 */
function talibMa(Module: TalibModule, name: 'EMA' | 'SMA', input: number[], period: number) {
  const n = input.length;
  const out: (number | null)[] = new Array(n).fill(null);
  if (n === 0) return out;
  const fnName = `TA_${name}`;
  if (!cwrapped[fnName]) {
    cwrapped[fnName] = Module.cwrap(fnName, 'number', [
      'number', 'number', 'number', 'number', 'number', 'number', 'number',
    ]);
  }
  const fn = cwrapped[fnName];
  const inPtr = Module._malloc(n * 8);
  const outPtr = Module._malloc(n * 8);
  const begPtr = Module._malloc(4);
  const nbPtr = Module._malloc(4);
  try {
    Module.HEAPF64.set(new Float64Array(input), inPtr / 8);
    const rc = fn(0, n - 1, inPtr, period, begPtr, nbPtr, outPtr);
    if (rc !== 0) throw new Error(`${fnName} return code ${rc}`);
    const beg = Module.HEAP32[begPtr >> 2];
    const nb = Module.HEAP32[nbPtr >> 2];
    for (let i = 0; i < nb; i++) out[beg + i] = Module.HEAPF64[(outPtr >> 3) + i];
  } finally {
    Module._free(inPtr);
    Module._free(outPtr);
    Module._free(begPtr);
    Module._free(nbPtr);
  }
  return out;
}

