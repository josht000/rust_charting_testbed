// Pure-JS reference implementations (port of shared/indicators/src/lib.rs)
// ---------------------------------------------------------------------------

/** TA-Lib-style EMA: seeded with SMA of first `period` values, k = 2/(p+1). */
export function ema(data: number[], period: number): (number | null)[] {
  const out: (number | null)[] = new Array(data.length).fill(null);
  if (data.length < period || period === 0) return out;
  const k = 2 / (period + 1);
  let prev = 0;
  for (let i = 0; i < period; i++) prev += data[i];
  prev /= period;
  out[period - 1] = prev;
  for (let i = period; i < data.length; i++) {
    prev = data[i] * k + prev * (1 - k);
    out[i] = prev;
  }
  return out;
}

/** Simple moving average. First `period-1` outputs are null. */
export function sma(data: number[], period: number): (number | null)[] {
  const out: (number | null)[] = new Array(data.length).fill(null);
  if (data.length < period || period === 0) return out;
  let sum = 0;
  for (let i = 0; i < period; i++) sum += data[i];
  out[period - 1] = sum / period;
  for (let i = period; i < data.length; i++) {
    sum += data[i] - data[i - period];
    out[i] = sum / period;
  }
  return out;
}

/** VWAP resetting at each new calendar day (ts/86400 changes). */
export function vwapDaily(bars: Bar[]): (number | null)[] {
  const out: (number | null)[] = new Array(bars.length);
  let day = -1;
  let pv = 0;
  let vv = 0;
  for (let i = 0; i < bars.length; i++) {
    const b = bars[i];
    const d = Math.floor(b.ts / 86400);
    if (d !== day) {
      day = d;
      pv = 0;
      vv = 0;
    }
    const tp = (b.high + b.low + b.close) / 3;
    pv += tp * b.volume;
    vv += b.volume;
    out[i] = vv > 0 ? pv / vv : tp;
  }
  return out;
}

/**
 * Horizontal volume profile over the last `lookback` bars: `bins` price bins
 * spanning [min low, max high]; each bar's volume goes to the bin holding its
 * close.
 */
export function volumeProfile(bars: Bar[], lookback: number, bins: number): ProfileBin[] {
  const start = Math.max(0, bars.length - lookback);
  const slice = bars.slice(start);
  if (slice.length === 0 || bins === 0) return [];
  let lo = Infinity;
  let hi = -Infinity;
  for (const b of slice) {
    if (b.low < lo) lo = b.low;
    if (b.high > hi) hi = b.high;
  }
  const step = hi > lo ? (hi - lo) / bins : 1;
  const out: ProfileBin[] = [];
  for (let i = 0; i < bins; i++) {
    out.push({ price_low: lo + i * step, price_high: lo + (i + 1) * step, volume: 0 });
  }
  for (const b of slice) {
    let idx = Math.floor((b.close - lo) / step);
    if (idx > bins - 1) idx = bins - 1;
    if (idx < 0) idx = 0;
    out[idx].volume += b.volume;
  }
  return out;
}

export function computeAllJs(bars: Bar[]): Indicators {
  const closes = bars.map((b) => b.close);
  return {
    ema10: ema(closes, 10),
    ema20: ema(closes, 20),
    ema50: ema(closes, 50),
    sma200: sma(closes, 200),
    vwap: vwapDaily(bars),
    profile: volumeProfile(bars, 2000, 40),
  };
}

