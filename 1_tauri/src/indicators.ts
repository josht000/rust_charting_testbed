/**
 * All six indicators; EMA/SMA via TA-Lib WASM, VWAP/profile via JS.
 * `moduleOverride` lets tests inject the emscripten module loaded via
 * createRequire (vitest's CJS interop can't unwrap the factory export).
 */
export async function computeAllTalib(bars: Bar[], moduleOverride?: TalibModule): Promise<Indicators> {
  const M = moduleOverride ?? (await initTalib());
  const closes = bars.map((b) => b.close);
  return {
    ema10: talibMa(M, 'EMA', closes, 10),
    ema20: talibMa(M, 'EMA', closes, 20),
    ema50: talibMa(M, 'EMA', closes, 50),
    sma200: talibMa(M, 'SMA', closes, 200),
    vwap: vwapDaily(bars),
    profile: volumeProfile(bars, 2000, 40),
  };
}
